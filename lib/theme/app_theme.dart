    switch (status.toLowerCase()) {
      case 'success':
      case 'active':
      case 'available':
        return isLight ? successLight : successDark;
      case 'warning':
      case 'expiring':
      case 'low_stock':
        return isLight ? warningLight : warningDark;
      case 'error':
      case 'expired':
      case 'out_of_stock':
        return isLight ? errorLight : errorDark;
      default:
        return isLight ? textSecondaryLight : textSecondaryDark;
    }
  }
}
